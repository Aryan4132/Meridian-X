import datetime
import re

def get_temporal_system_context() -> str:
    """
    Generates dynamic temporal metadata anchored to the current system local time.
    Prevents LLM agents and QA auditors from using pre-trained static knowledge cutoffs
    to reject real-time facts or search results.
    """
    now = datetime.datetime.now()
    current_date_str = now.strftime("%B %d, %Y")  # e.g., "July 28, 2026"
    iso_date_str = now.strftime("%Y-%m-%d")       # e.g., "2026-07-28"

    return f"""
### TEMPORAL METADATA & GROUND TRUTH
- Current Local Date: {current_date_str} (ISO: {iso_date_str}).
- Year: {now.year}
- Any events, dates, or search results occurring on or before {current_date_str} represent REAL-TIME PRESENT OR HISTORICAL FACTS.
- NEVER classify dates on or before {current_date_str} as "future dates", "temporal errors", or "hallucinations".
- The model's pre-training cutoff date MUST BE OVERRIDDEN by live tool execution results (e.g., search_news, search_web).
"""

def build_qa_reviewer_prompt(agent_plan: str, tool_outputs: str, proposed_response: str) -> str:
    """
    Constructs an auditor prompt for the QA Reviewer in the consensus debate loop,
    explicitly instructing it to accept real-time web search results for the current date.
    """
    temporal_context = get_temporal_system_context()
    now_str = datetime.datetime.now().strftime("%Y-%m-%d")

    return f"""You are an Expert QA Auditor evaluating an AI Agent's response.

{temporal_context}

### AUDIT RULES & VERIFICATION CONSTRAINTS
1. REAL-TIME TOOL PRIORITY: If the agent executed a web search or news tool, facts retrieved for dates up to {now_str} are VALID and must be trusted over your internal training data cutoff.
2. DO NOT GENERATE TEMPORAL HALLUCINATION CRITIQUES: Do not mark dates in the year {datetime.datetime.now().year} as future hallucinations if they match the current system date ({now_str}).
3. Only reject responses if there is an actual logical contradiction, unsanitized executable payload, or security violation.

Agent Plan:
{agent_plan}

Tool Outputs:
{tool_outputs}

Proposed Response:
{proposed_response}

Evaluate the response and output JSON:
{{
  "pass": true,
  "critique": "OK"
}}
"""

def sanitize_qa_critique(qa_result: dict, current_year: int = None) -> dict:
    """
    Filters out false-positive temporal cutoff critiques generated by the QA auditor LLM.
    If the QA auditor erroneously flags a current date as a future hallucination, this
    filter neutralizes the critique and approves the agent output.
    """
    if current_year is None:
        current_year = datetime.datetime.now().year

    if not qa_result.get("pass", True):
        critique = qa_result.get("critique", "")

        # Check if the critique is a false positive about the current year being a "future date"
        is_temporal_false_positive = any([
            "Temporal Error" in critique and str(current_year) in critique,
            "future date" in critique.lower() and str(current_year) in critique,
            "fabricating" in critique.lower() and str(current_year) in critique
        ])

        if is_temporal_false_positive:
            return {
                "pass": True,
                "critique": f"OVERRIDDEN: Ignored false-positive temporal critique regarding current year {current_year}."
            }

    return qa_result

